import '../models/wedding_budget_item.dart';

/// 60개 표준 결혼 예산 마스터 템플릿 모델
class WeddingBudgetMasterTemplate {
  const WeddingBudgetMasterTemplate({
    required this.id,
    required this.orderIndex,
    required this.category,
    required this.title,
    this.defaultEstimatedBudget = 0,
    this.defaultDeposit = 0,
    this.defaultBalance = 0,
    this.defaultPayer = ExpensePayer.joint,
    this.tip = '',
  });

  final String id;
  final int orderIndex;
  final WeddingBudgetCategory category;
  final String title;
  final int defaultEstimatedBudget;
  final int defaultDeposit;
  final int defaultBalance;
  final ExpensePayer defaultPayer;
  final String tip;

  /// 예산 항목 인스턴스로 변환
  WeddingBudgetItem toBudgetItem({String? customId}) {
    return WeddingBudgetItem(
      id: customId ?? 'budget-tpl-$id-${DateTime.now().microsecondsSinceEpoch}',
      title: title,
      category: category,
      estimatedBudget: defaultEstimatedBudget,
      deposit: defaultDeposit,
      balance: defaultBalance,
      payer: defaultPayer,
      status: defaultDeposit > 0 ? BudgetPaymentStatus.contracted : BudgetPaymentStatus.pending,
      memo: tip,
    );
  }
}

